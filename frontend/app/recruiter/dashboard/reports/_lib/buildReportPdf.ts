import fs from "fs";
import path from "path";

import { jsPDF } from "jspdf";

import { ReportData, ReportDetail } from "@/app/common/types/reports.type";
import { formatDate, formatDateRange, formatDays, formatHours, formatNaira, formatPercent } from "./format";

// Brand palette -- non-negotiable per spec. Native jsPDF drawing (text/rect/
// line) rather than the html2canvas-screenshot technique used elsewhere in
// this codebase for certificates -- that approach rasterizes every page
// into a PNG and would balloon a multi-section report into multiple MB,
// which conflicts directly with the "smallest possible file size" goal.
const NAVY: [number, number, number] = [26, 60, 94];
const LIGHT_NAVY: [number, number, number] = [45, 95, 138];
const GREEN: [number, number, number] = [29, 158, 117];
const LIGHT_GREY: [number, number, number] = [244, 244, 244];
const TEXT_GREY: [number, number, number] = [68, 68, 68];
const MUTED_GREY: [number, number, number] = [158, 158, 158];
const GRID_GREY: [number, number, number] = [224, 224, 224];
const AMBER: [number, number, number] = [181, 71, 8];
const RED: [number, number, number] = [181, 53, 53];
const WHITE: [number, number, number] = [255, 255, 255];

const rateColor = (rate: number): [number, number, number] => (rate >= 80 ? GREEN : rate >= 50 ? AMBER : RED);

const PAGE_W = 595.28; // A4 pt
const PAGE_H = 841.89;
const MARGIN = 48;
const HEADER_H = 40;
const FOOTER_H = 30;
const CONTENT_TOP = HEADER_H + 20;
const CONTENT_BOTTOM = PAGE_H - FOOTER_H - 10;

function loadLogoDataUrl(filename: string): string {
  const filePath = path.join(process.cwd(), "public", "emails", "assets", filename);
  const buffer = fs.readFileSync(filePath);
  return `data:image/png;base64,${buffer.toString("base64")}`;
}

type PdfContext = {
  doc: jsPDF;
  y: number;
  page: number;
  reportName: string;
  orgName: string;
  logoNavyDataUrl: string;
};

function newPage(ctx: PdfContext) {
  ctx.doc.addPage();
  ctx.page += 1;
  drawHeader(ctx);
  drawFooter(ctx);
  ctx.y = CONTENT_TOP;
}

function ensureSpace(ctx: PdfContext, neededHeight: number) {
  if (ctx.y + neededHeight > CONTENT_BOTTOM) {
    newPage(ctx);
  }
}

function drawHeader(ctx: PdfContext) {
  const { doc } = ctx;
  try {
    doc.addImage(ctx.logoNavyDataUrl, "PNG", MARGIN, 10, 56, 20);
  } catch {
    // Logo embed is best-effort -- a missing/unreadable asset shouldn't fail the whole export.
  }
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...MUTED_GREY);
  doc.text(ctx.reportName, PAGE_W - MARGIN, 22, { align: "right" });
  doc.setDrawColor(...NAVY);
  doc.setLineWidth(1);
  doc.line(0, HEADER_H, PAGE_W, HEADER_H);
}

function drawFooter(ctx: PdfContext) {
  const { doc, page } = ctx;
  const footerY = PAGE_H - FOOTER_H + 5;
  doc.setDrawColor(...GRID_GREY);
  doc.setLineWidth(0.5);
  doc.line(0, PAGE_H - FOOTER_H, PAGE_W, PAGE_H - FOOTER_H);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(...MUTED_GREY);
  doc.text(ctx.orgName, MARGIN, footerY);
  doc.text(`Page ${page}`, PAGE_W / 2, footerY, { align: "center" });
  doc.text("Generated by Tiaago", PAGE_W - MARGIN, footerY, { align: "right" });
}

function drawCoverPage(
  doc: jsPDF,
  report: ReportDetail,
  data: ReportData,
  recruiterName: string,
  logoWhiteDataUrl: string
) {
  const topH = PAGE_H * 0.4;
  const midH = PAGE_H * 0.45;

  doc.setFillColor(...NAVY);
  doc.rect(0, 0, PAGE_W, topH, "F");
  try {
    doc.addImage(logoWhiteDataUrl, "PNG", MARGIN, 32, 84, 30);
  } catch {
    // best-effort, see drawHeader
  }
  doc.setFont("helvetica", "bold");
  doc.setFontSize(28);
  doc.setTextColor(...WHITE);
  doc.text("Hiring Performance Report", PAGE_W / 2, topH / 2 + 20, { align: "center" });
  doc.setDrawColor(...WHITE);
  doc.setLineWidth(1);
  doc.line(PAGE_W / 2 - 80, topH / 2 + 40, PAGE_W / 2 + 80, topH / 2 + 40);

  doc.setFillColor(...WHITE);
  doc.rect(0, topH, PAGE_W, midH, "F");
  let y = topH + 60;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(...NAVY);
  doc.text(report.name, PAGE_W / 2, y, { align: "center" });
  y += 28;
  doc.setFontSize(14);
  doc.text(data.organisation.name, PAGE_W / 2, y, { align: "center" });
  y += 36;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(...TEXT_GREY);
  const infoLines = [
    `Prepared for: ${recruiterName}`,
    `Date range: ${formatDateRange(data.date_from, data.date_to)}`,
    `Roles included: ${data.roles.map(r => r.title).join(", ") || "None"}`,
    `Generated: ${new Date(data.generated_at).toLocaleString()}`,
  ];
  infoLines.forEach(line => {
    doc.text(line, PAGE_W / 2, y, { align: "center", maxWidth: PAGE_W - MARGIN * 4 });
    y += 20;
  });

  doc.setFillColor(...LIGHT_GREY);
  doc.rect(0, topH + midH, PAGE_W, PAGE_H - topH - midH, "F");
  const bottomCenterY = topH + midH + (PAGE_H - topH - midH) / 2;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...MUTED_GREY);
  doc.text("tiaago.com", PAGE_W / 2, bottomCenterY - 6, { align: "center" });
  doc.setFont("helvetica", "italic");
  doc.text("The Operating System for Hiring", PAGE_W / 2, bottomCenterY + 8, { align: "center" });
}

function sectionTitle(ctx: PdfContext, title: string) {
  ensureSpace(ctx, 40);
  const { doc } = ctx;
  doc.setFillColor(...NAVY);
  doc.rect(MARGIN, ctx.y, 3, 18, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(...NAVY);
  doc.text(title, MARGIN + 12, ctx.y + 14);
  ctx.y += 32;
}

function drawExecutiveSummary(ctx: PdfContext, data: ReportData) {
  sectionTitle(ctx, "Executive Summary");
  const { doc } = ctx;
  const s = data.summary;
  const blocks: { value: string; label: string }[] = [
    { value: String(s.total_roles), label: "Total roles in report" },
    { value: String(s.total_applied), label: "Total candidates applied" },
    { value: String(s.total_screened_passed), label: "Passed screening" },
    { value: formatPercent(s.screening_pass_rate), label: "Screening pass rate" },
    { value: String(s.total_assessments), label: "Total assessments" },
    { value: formatNaira(s.avg_cost_per_candidate), label: "Avg. cost per candidate" },
    { value: s.avg_cost_per_role_filled != null ? formatNaira(s.avg_cost_per_role_filled) : "N/A", label: "Avg. cost per role filled" },
    { value: s.avg_days_posted_to_filled != null ? formatDays(Math.round(s.avg_days_posted_to_filled)) : "N/A", label: "Avg. days to fill" },
  ];

  const cols = 2;
  const gap = 12;
  const blockW = (PAGE_W - MARGIN * 2 - gap) / cols;
  const blockH = 56;

  blocks.forEach((block, i) => {
    const col = i % cols;
    if (col === 0) ensureSpace(ctx, blockH + gap);
    const x = MARGIN + col * (blockW + gap);
    doc.setDrawColor(...GRID_GREY);
    doc.setLineWidth(0.5);
    doc.setFillColor(...WHITE);
    doc.roundedRect(x, ctx.y, blockW, blockH, 4, 4, "FD");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(20);
    doc.setTextColor(...NAVY);
    doc.text(block.value, x + 12, ctx.y + 26);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...MUTED_GREY);
    doc.text(block.label, x + 12, ctx.y + 42, { maxWidth: blockW - 24 });
    if (col === cols - 1 || i === blocks.length - 1) {
      ctx.y += blockH + gap;
    }
  });
}

function drawFunnel(ctx: PdfContext, stages: { label: string; count: number }[]) {
  const { doc } = ctx;
  const max = stages[0]?.count || 1;
  const barX = MARGIN + 110;
  const barMaxW = PAGE_W - MARGIN - barX - 70;
  const rowH = 18;

  stages.forEach(stage => {
    ensureSpace(ctx, rowH);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...TEXT_GREY);
    doc.text(stage.label, MARGIN + 105, ctx.y + 10, { align: "right" });
    doc.setFillColor(...LIGHT_GREY);
    doc.rect(barX, ctx.y, barMaxW, 12, "F");
    const w = Math.max(4, (stage.count / max) * barMaxW);
    doc.setFillColor(...NAVY);
    doc.rect(barX, ctx.y, w, 12, "F");
    doc.setTextColor(...TEXT_GREY);
    doc.text(String(stage.count), barX + barMaxW + 8, ctx.y + 10);
    ctx.y += rowH;
  });
  ctx.y += 8;
}

type TableColumn = { header: string; width: number; align?: "left" | "right" };

function drawTable(ctx: PdfContext, columns: TableColumn[], rows: string[][]) {
  const { doc } = ctx;
  const rowH = 20;
  ensureSpace(ctx, rowH);

  let x = MARGIN;
  doc.setFillColor(...NAVY);
  doc.rect(MARGIN, ctx.y, columns.reduce((a, c) => a + c.width, 0), rowH, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(...WHITE);
  columns.forEach(col => {
    doc.text(col.header, col.align === "right" ? x + col.width - 6 : x + 6, ctx.y + 13, {
      align: col.align === "right" ? "right" : "left",
    });
    x += col.width;
  });
  ctx.y += rowH;

  rows.forEach((row, rowIndex) => {
    ensureSpace(ctx, rowH);
    const tableW = columns.reduce((a, c) => a + c.width, 0);
    if (rowIndex % 2 === 1) {
      doc.setFillColor(...LIGHT_GREY);
      doc.rect(MARGIN, ctx.y, tableW, rowH, "F");
    }
    doc.setDrawColor(...GRID_GREY);
    doc.setLineWidth(0.5);
    doc.line(MARGIN, ctx.y + rowH, MARGIN + tableW, ctx.y + rowH);
    x = MARGIN;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...TEXT_GREY);
    row.forEach((cell, i) => {
      const col = columns[i];
      doc.text(cell, col.align === "right" ? x + col.width - 6 : x + 6, ctx.y + 13, {
        align: col.align === "right" ? "right" : "left",
      });
      x += col.width;
    });
    ctx.y += rowH;
  });
  ctx.y += 12;
}

const FUNNEL_LABELS: Record<string, string> = {
  applied: "Applied",
  screened: "Screened",
  assessment_sent: "Assessment Sent",
  assessment_completed: "Assessment Completed",
  interviewed: "Interviewed",
  filled: "Filled",
};

export async function buildReportPdf(report: ReportDetail, recruiterName: string): Promise<Buffer> {
  const data = report.report_data;
  if (!data) throw new Error("Report has no data to export.");

  const doc = new jsPDF({ unit: "pt", format: "a4", compress: true });
  const logoNavyDataUrl = loadLogoDataUrl("Tiaago_logo.png");
  const logoWhiteDataUrl = loadLogoDataUrl("Tiaago_logo_white.png");

  drawCoverPage(doc, report, data, recruiterName, logoWhiteDataUrl);

  const ctx: PdfContext = { doc, y: CONTENT_TOP, page: 1, reportName: report.name, orgName: data.organisation.name, logoNavyDataUrl };
  newPage(ctx); // page 2: header/footer + executive summary

  drawExecutiveSummary(ctx, data);

  // Section 2 -- role by role
  sectionTitle(ctx, "Role by Role Breakdown");
  data.roles.forEach(role => {
    ensureSpace(ctx, 60);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(...NAVY);
    doc.text(role.title, MARGIN, ctx.y + 10);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...MUTED_GREY);
    doc.text(
      `Posted ${formatDate(role.date_posted)} - ${role.date_filled ? `Filled ${formatDate(role.date_filled)}` : "Active"} - ${role.status_label}`,
      MARGIN,
      ctx.y + 24
    );
    ctx.y += 36;

    drawFunnel(
      ctx,
      Object.entries(role.funnel).map(([key, count]) => ({ label: FUNNEL_LABELS[key] || key, count }))
    );

    drawTable(
      ctx,
      [{ header: "Cost line", width: 300 }, { header: "Count", width: 80, align: "right" }, { header: "Total", width: 130, align: "right" }],
      [
        ["Resume screenings", String(role.cost.resume_screening.count), formatNaira(role.cost.resume_screening.total)],
        ["Assessments", String(role.cost.assessment.count), formatNaira(role.cost.assessment.total)],
        ["AI interviews", String(role.cost.ai_interview.count), formatNaira(role.cost.ai_interview.total)],
        ["Human interviews", String(role.cost.human_interview.count), formatNaira(role.cost.human_interview.total)],
        ["Recording add-ons", String(role.cost.recording.count), formatNaira(role.cost.recording.total)],
        ["Role total", "", formatNaira(role.cost.role_total)],
      ]
    );
  });

  // Section 3 -- combined pipeline
  sectionTitle(ctx, "Pipeline Performance");
  drawFunnel(
    ctx,
    Object.entries(data.pipeline.combined_funnel).map(([key, count]) => ({ label: FUNNEL_LABELS[key] || key, count }))
  );
  drawTable(
    ctx,
    [{ header: "Role", width: 220 }, { header: "Pass rate", width: 110, align: "right" }, { header: "Avg. score", width: 180, align: "right" }],
    data.pipeline.screening_performance.map(r => [r.title, formatPercent(r.pass_rate), r.avg_score != null ? String(r.avg_score) : "N/A"])
  );

  // Section 4 -- cost analysis
  sectionTitle(ctx, "Cost Analysis");
  drawTable(
    ctx,
    [{ header: "Category", width: 300 }, { header: "Total (NGN)", width: 210, align: "right" }],
    [
      ["Resume screening", formatNaira(data.costs.breakdown.resume_screening)],
      ["Assessments", formatNaira(data.costs.breakdown.assessment)],
      ["AI interviews", formatNaira(data.costs.breakdown.ai_interview)],
      ["Human interviews", formatNaira(data.costs.breakdown.human_interview)],
      ["Recording add-ons", formatNaira(data.costs.breakdown.recording)],
      ["Grand total", formatNaira(data.costs.grand_total)],
    ]
  );
  drawTable(
    ctx,
    [
      { header: "Role", width: 170 },
      { header: "Candidates", width: 90, align: "right" },
      { header: "Cost", width: 110, align: "right" },
      { header: "Placements", width: 80, align: "right" },
      { header: "Cost/Placement", width: 60, align: "right" },
    ],
    data.costs.cost_efficiency.map(r => [
      r.title,
      String(r.candidates),
      formatNaira(r.cost),
      String(r.placements),
      r.cost_per_placement != null ? formatNaira(r.cost_per_placement) : "N/A",
    ])
  );

  // Section 5 -- time analysis
  sectionTitle(ctx, "Time Analysis");
  Object.values(data.time.stage_durations).forEach(stage => {
    ensureSpace(ctx, 18);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...TEXT_GREY);
    doc.text(`${stage.label}: ${formatHours(stage.avg_hours)}`, MARGIN, ctx.y + 10);
    ctx.y += 18;
  });
  ctx.y += 8;
  if (data.time.time_to_fill.length) {
    drawTable(
      ctx,
      [{ header: "Role", width: 300 }, { header: "Days to fill", width: 100, align: "right" }, { header: "vs. benchmark", width: 110, align: "right" }],
      data.time.time_to_fill.map(r => [r.title, formatDays(r.days_to_fill), r.beats_benchmark ? "Beats" : "Above"])
    );
  }

  // Section 6 -- candidate experience
  sectionTitle(ctx, "Candidate Experience Data");
  drawTable(
    ctx,
    [
      { header: "Stage", width: 220 },
      { header: "Entered", width: 90, align: "right" },
      { header: "Left", width: 90, align: "right" },
      { header: "Drop-off", width: 110, align: "right" },
    ],
    data.experience.drop_off_analysis.map(r => [r.stage, String(r.entered), String(r.left), formatPercent(r.drop_off_rate)])
  );
  ensureSpace(ctx, 40);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...rateColor(data.experience.feedback.rate));
  doc.text(
    `Feedback sent rate: ${formatPercent(data.experience.feedback.rate)} (${data.experience.feedback.sent_count} of ${data.experience.feedback.total_interviewed} interviewed)`,
    MARGIN,
    ctx.y + 10
  );

  return Buffer.from(doc.output("arraybuffer"));
}

export function reportPdfFilename(report: ReportDetail): string {
  const range = `${report.date_from} to ${report.date_to}`;
  return `Tiaago Report - ${report.report_data?.organisation.name || "Report"} - ${range}.pdf`;
}
